import AppKit
import ImageIO

@MainActor enum Clipboard {
    static let supported: Set<String> = Set(["public.utf8-plain-text", "public.utf16-external-plain-text", "public.rtf", "public.html", "public.url", "public.file-url"] + ClipFormat.imageTypes).union(ClipFormat.markdownTypes)
    static func supports(_ type: String) -> Bool { supported.contains(type) || ClipFormat.isSourceText(type) }
    static let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.1password.1password", "de.petermaurer.TransientPasteboardType"]
    static func read(_ board: NSPasteboard) throws -> CapturedClip? {
        let generation = board.changeCount
        guard let originals = board.pasteboardItems, !originals.isEmpty else { throw ShiyingError.unreadable }
        guard originals.count <= 256 else { throw ShiyingError.tooLarge }
        if originals.contains(where: { !$0.types.map(\.rawValue).filter(sensitive.contains).isEmpty }) { return nil }
        var items: [ClipItem] = []; var total = 0; var textBytes = 0; var partial = false
        for original in originals {
            var reps: [Representation] = []
            for type in original.types.sorted(by: { $0.rawValue < $1.rawValue }) {
                guard supports(type.rawValue) else { partial = true; continue }
                guard let bytes = original.data(forType: type) else { partial = true; continue }
                total += bytes.count
                if ["public.utf8-plain-text", "public.utf16-external-plain-text", "public.rtf", "public.html", "public.url"].contains(type.rawValue) || ClipFormat.isSourceText(type.rawValue) { textBytes += bytes.count }
                guard total <= 32 * 1_024 * 1_024, textBytes <= 1_024 * 1_024 else { throw ShiyingError.tooLarge }
                if ClipFormat.imageTypes.contains(type.rawValue) { _ = try ImageBounds.dimensions(bytes) }
                if type.rawValue == "public.file-url" {
                    guard let text = String(data: bytes, encoding: .utf8), let url = URL(string: text), url.isFileURL else { throw ShiyingError.unreadable }
                }
                reps.append(Representation(type: type.rawValue, data: bytes))
            }
            guard !reps.isEmpty else { throw ShiyingError.unsupported }
            // A safe plain-text fallback never invokes an HTML renderer or remote resources.
            if !reps.contains(where: { $0.type == "public.utf8-plain-text" }) {
                var fallback: String?
                if let bytes = reps.first(where: { ClipFormat.isSourceText($0.type) })?.data { fallback = String(data: bytes, encoding: .utf8) }
                if let bytes = reps.first(where: { $0.type == "public.utf16-external-plain-text" })?.data { fallback = String(data: bytes, encoding: .utf16) }
                if fallback == nil, let bytes = reps.first(where: { $0.type == "public.rtf" })?.data { fallback = NSAttributedString(rtf: bytes, documentAttributes: nil)?.string }
                if fallback == nil, let bytes = reps.first(where: { $0.type == "public.html" })?.data, let html = String(data: bytes, encoding: .utf8) {
                    fallback = html.replacingOccurrences(of: "(?is)<(script|style)\\b[^>]*>.*?</\\1>", with: "", options: .regularExpression)
                        .replacingOccurrences(of: "(?is)<[^>]+>", with: " ", options: .regularExpression)
                        .replacingOccurrences(of: "&nbsp;", with: " ").replacingOccurrences(of: "&lt;", with: "<").replacingOccurrences(of: "&gt;", with: ">").replacingOccurrences(of: "&amp;", with: "&")
                }
                if fallback == nil, let bytes = reps.first(where: { $0.type == "public.url" })?.data { fallback = String(data: bytes, encoding: .utf8) }
                if let fallback {
                    let data = Data(fallback.utf8); total += data.count; textBytes += data.count
                    guard textBytes <= 1_024 * 1_024, total <= 32 * 1_024 * 1_024 else { throw ShiyingError.tooLarge }
                    reps.append(Representation(type: "public.utf8-plain-text", data: data))
                }
            }
            items.append(ClipItem(representations: reps.sorted(by: { $0.type < $1.type })))
        }
        guard board.changeCount == generation else { return nil }
        let payload = ClipPayload(items: items)
        let text = payload.plainText ?? ""
        let files = payload.fileURLs
        let image = ClipFormat.imageData(in: payload)
        var width: Int?; var height: Int?
        let kind: ClipKind
        if !files.isEmpty { kind = .file }
        else if let image {
            kind = .image
            let (w, h) = try ImageBounds.dimensions(image)
            width = w; height = h
        } else if let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)), ["https", "http", "mailto"].contains(url.scheme?.lowercased() ?? "") { kind = .link }
        else { kind = .text }
        let lines = text.split(whereSeparator: \.isNewline)
        let title: String
        if kind == .file { title = files.map(\.lastPathComponent).joined(separator: ", ") }
        else if kind == .link { title = URL(string: text)?.host ?? text }
        else { title = String(lines.first?.prefix(160) ?? "") }
        let detail = kind == .file ? files.map(\.lastPathComponent).joined(separator: " · ") : String(lines.dropFirst().joined(separator: " ").prefix(320))
        return CapturedClip(kind: kind, payload: payload, summary: ClipSummary(title: String(title.prefix(320)), detail: detail, hasText: payload.plainText != nil, pixelWidth: width, pixelHeight: height, format: ClipFormat.detect(payload, kind: kind)), partial: partial)
    }
    static func write(_ payload: ClipPayload, plain: Bool, to board: NSPasteboard = .general) throws -> Int {
        let items: [NSPasteboardItem]
        if plain {
            guard let text = payload.plainText else { throw ShiyingError.unsupported }
            let item = NSPasteboardItem(); guard item.setString(text, forType: .string) else { throw ShiyingError.write }; items = [item]
        } else {
            items = try payload.items.map { source in
                let item = NSPasteboardItem()
                for rep in source.representations {
                    guard supports(rep.type), item.setData(rep.data, forType: .init(rep.type)) else { throw ShiyingError.write }
                }
                return item
            }
        }
        guard !items.isEmpty else { throw ShiyingError.write }
        board.prepareForNewContents(with: .currentHostOnly)
        guard board.writeObjects(items) else { throw ShiyingError.write }
        return board.changeCount
    }
}

enum ImageBounds {
    static func dimensions(_ data: Data) throws -> (Int, Int) {
        guard let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
            let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
            let width = props[kCGImagePropertyPixelWidth] as? Int, let height = props[kCGImagePropertyPixelHeight] as? Int,
            width > 0, height > 0 else { throw ShiyingError.unreadable }
        guard width <= 40_000_000 / height else { throw ShiyingError.tooLarge }
        return (width, height)
    }
}

actor ThumbnailMaker {
    func make(_ payload: ClipPayload) -> CGImage? {
        guard let data = ClipFormat.imageData(in: payload),
            let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
            let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
            let width = props[kCGImagePropertyPixelWidth] as? Int, let height = props[kCGImagePropertyPixelHeight] as? Int,
            width > 0, height > 0, width <= 40_000_000 / height else { return nil }
        return CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 320, kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true] as CFDictionary)
    }
}
